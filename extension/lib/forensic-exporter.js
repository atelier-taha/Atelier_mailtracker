  'use strict';

  /**
   * Generates a SIEM / SOC-ready Technical JSON Dossier
   */
  function exportAsJson(parsedData, authData, spoofData) {
    const dossier = {
      version: '1.0.0',
      generator: "Atelier's MailTracker — Mail Intelligence Suite",
      generatedAt: new Date().toISOString(),
      threatAssessment: {
        score: spoofData.threatScore,
        riskLevel: spoofData.riskLevel,
        isSpoofed: spoofData.isSpoofed,
        findings: spoofData.findings
      },
      emailMetadata: {
        subject: parsedData.summary.subject,
        messageId: parsedData.summary.messageId,
        date: parsedData.summary.date,
        from: parsedData.summary.from,
        to: parsedData.summary.to,
        returnPath: parsedData.summary.returnPath,
        replyTo: parsedData.summary.replyTo
      },
      authentication: {
        verdict: authData.verdict,
        spf: authData.spf,
        dkim: authData.dkim,
        dmarc: authData.dmarc,
        alignment: authData.alignment
      },
      transmissionHops: {
        totalHops: parsedData.hops.length,
        hopList: parsedData.hops.map(h => ({
          hopNumber: h.hopNumber,
          fromMta: h.fromMta,
          byMta: h.byMta,
          ip: h.ip,
          rdns: h.rdns,
          protocol: h.protocol,
          deltaTimeSeconds: h.deltaTimeSeconds,
          clockSkewAnomaly: h.clockSkewAnomaly,
          delayAnomaly: h.delayAnomaly,
          timestamp: h.timestamp ? new Date(h.timestamp).toISOString() : null,
          rawDate: h.rawDate
        }))
      },
      rawHeaders: parsedData.headers
    };

    return JSON.stringify(dossier, null, 2);
  }

  /**
   * Generates a Formatted Markdown Audit Dossier
   */
  function exportAsMarkdown(parsedData, authData, spoofData) {
    const s = parsedData.summary;
    const now = new Date().toUTCString();

    let md = `# 🛡️ Forensic Email Intelligence Report\n`;
    md += `**Generated by:** Atelier's MailTracker — Mail Intelligence\n`;
    md += `**Date:** ${now}\n\n`;

    md += `## 1. Executive Threat Assessment\n\n`;
    md += `| Metric | Assessment |\n`;
    md += `| :--- | :--- |\n`;
    md += `| **Threat Score** | **${spoofData.threatScore} / 100** |\n`;
    md += `| **Risk Classification** | **${spoofData.riskLevel}** |\n`;
    md += `| **Authentication Verdict** | **${authData.verdict}** |\n`;
    md += `| **Transmission Hops** | **${parsedData.hops.length} Hops** |\n\n`;

    if (spoofData.findings.length > 0) {
      md += `### ⚠️ Identified Threat Indicators\n\n`;
      spoofData.findings.forEach(f => {
        md += `- **[${f.severity}] ${f.title}**: ${f.description}\n`;
      });
      md += `\n`;
    } else {
      md += `*No spoofing or phishing anomalies detected. Domain authentication aligned.*\n\n`;
    }

    md += `## 2. Message Envelope & Headers\n\n`;
    md += `- **Subject:** ${s.subject}\n`;
    md += `- **From (Header):** \`${s.from.raw}\`\n`;
    md += `- **Return-Path (Envelope):** \`${s.returnPath.raw || 'None'}\`\n`;
    md += `- **Reply-To:** \`${s.replyTo.raw || 'None'}\`\n`;
    md += `- **To:** \`${s.to.raw || 'None'}\`\n`;
    md += `- **Date:** ${s.date}\n`;
    md += `- **Message-ID:** \`${s.messageId || 'None'}\`\n\n`;

    md += `## 3. Domain Authentication Matrix\n\n`;
    md += `| Protocol | Status | Domain | Alignment | Verdict |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- |\n`;
    md += `| **SPF** | \`${authData.spf.status}\` | \`${authData.spf.domain || 'N/A'}\` | ${authData.spf.aligned ? '✅ Aligned' : '❌ Unaligned'} | ${authData.spf.pass ? 'PASS' : 'FAIL'} |\n`;
    md += `| **DKIM** | \`${authData.dkim.status}\` | \`${authData.dkim.domain || 'N/A'}\` | ${authData.dkim.aligned ? '✅ Aligned' : '❌ Unaligned'} | ${authData.dkim.pass ? 'PASS' : 'FAIL'} |\n`;
    md += `| **DMARC** | \`${authData.dmarc.status}\` | \`${s.from.domain}\` | ${authData.dmarc.aligned ? '✅ Aligned' : '❌ Unaligned'} | ${authData.dmarc.computedPass ? 'PASS' : 'FAIL'} |\n\n`;

    md += `## 4. Transmission Hop Chronology\n\n`;
    md += `| Hop | Origin MTA | Receiving MTA | IP Address | Latency (Δt) | Anomalies |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;

    parsedData.hops.forEach(h => {
      const anomalies = [];
      if (h.clockSkewAnomaly) anomalies.push('⚠️ Clock Skew');
      if (h.delayAnomaly) anomalies.push('⏱️ High Delay');
      const anomalyStr = anomalies.length ? anomalies.join(', ') : 'None';
      const deltaStr = h.isOrigin ? 'Origin' : `${h.deltaTimeSeconds}s`;

      md += `| **${h.hopNumber}** | \`${h.fromMta || 'Unknown'}\` | \`${h.byMta || 'Unknown'}\` | \`${h.ip || 'Hidden'}\` | ${deltaStr} | ${anomalyStr} |\n`;
    });

    md += `\n---\n*Report generated via Atelier's MailTracker Mail Intelligence Suite*\n`;
    return md;
  }

